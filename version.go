package futsim

// Version 是本库**当前开发中**的版本，全仓唯一的那一个。
//
// ⚠️ 它不是装饰，它是「明确不建模」那一档的到期机制的另一半。
//
// design.md §5 要求每一处「不建模」都带到期版本，理由是
// **不带到期版本的「不建模」是一句永久豁免**。而 roadmap.md 自己点破了下一层：
//
//	⚠️ 声明一旦写下去，没有任何机制逼它在 v0.4.0 被摘掉。
//	一个「暂缓」会安静地变成永久。
//
// `TestNotModeledDeclarationsHaveNotExpired` 就是那个机制：
// 它扫全仓的 `Skip("vX.Y.Z", …)` 与 `NotModeledUntil: "vX.Y.Z"`，
// 只要某一处的到期版本**已经不晚于** Version，就红。
//
// 于是把 Version 往前推一个数，会**当场逼出**所有到期的欠账 ——
// 那正是发版时该发生的事，而不是发完版之后某天有人想起来。
// ⚠️ 20260909：从 `v0.1.0` 推到 `v0.4.0`。它在 v0.1.0 上停了两天，
// 而**停着的时候这个机制是空转的** —— 到期版本只要晚于 Version 就不会红，
// 而 Version 不动，任何声明都晚于它。
//
// 一个「到期机制」在它自己的基准不动时，与没有这个机制完全一样。
//
// 为什么是 v0.4.0：v0.1.0/v0.2.0 已合 main 且验收达成；v0.3.0 的验收
// （隔夜持仓的完整对拍）已达成，清单上剩的两项**是被这个口子堵死的**，
// 不是没做（平今费率与开仓同值、消耗顺序结构性测不出，见 state.md
// kq_facts 18/40）；v0.4.0 的报单校验与冻结已落地，`match` 待人裁决。
// 于是「当前开发中」是 v0.4.0。
const Version = "v0.4.0"
