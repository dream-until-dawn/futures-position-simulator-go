package futsim

// Version 是本库**当前开发中**的版本，全仓唯一的那一个。
//
// ⚠️ 它不是装饰，它是「明确不建模」那一档的到期机制的另一半。
//
// design.md §5 要求每一处「不建模」都带到期版本，理由是
// **不带到期版本的「不建模」是一句永久豁免**。而 roadmap.md 自己点破了下一层：
//
//	⚠️ 声明一旦写下去，没有任何机制逼它在 v0.4.0 被摘掉。
//	一个「暂缓」会安静地变成永久。
//
// `TestNotModeledDeclarationsHaveNotExpired` 就是那个机制：
// 它扫全仓的 `Skip("vX.Y.Z", …)` 与 `NotModeledUntil: "vX.Y.Z"`，
// 只要某一处的到期版本**已经不晚于** Version，就红。
//
// 于是把 Version 往前推一个数，会**当场逼出**所有到期的欠账 ——
// 那正是发版时该发生的事，而不是发完版之后某天有人想起来。
const Version = "v0.1.0"
